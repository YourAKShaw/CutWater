/**
 * Bundle src/cli.ts into the single zero-dependency file the skill ships:
 * skills/cutwater/scripts/cutwater.mjs (ESM, Node.js 18+).
 *
 *   node scripts/build.ts          write the bundle
 *   node scripts/build.ts --check  fail if the committed bundle is stale
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const outfile = `${root}skills/cutwater/scripts/cutwater.mjs`;
const banner = [
  "#!/usr/bin/env node",
  "// cutwater helper CLI. Generated by `npm run build` from src/ in",
  "// https://github.com/YourAKShaw/ThroughLine. Do not edit by hand.",
].join("\n");

const result = await build({
  entryPoints: [`${root}src/cli.ts`],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node18",
  write: false,
  legalComments: "none",
  charset: "utf8",
  banner: { js: banner },
  logLevel: "warning",
});

const output = result.outputFiles[0]?.text;
if (output === undefined) throw new Error("esbuild produced no output");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outfile, "utf8");
  } catch {
    // Missing bundle is reported as stale below.
  }
  if (current !== output) {
    console.error(
      "skills/cutwater/scripts/cutwater.mjs is out of date. Run `npm run build` and commit it.",
    );
    process.exit(1);
  }
  console.log("Bundle is up to date.");
} else {
  mkdirSync(new URL(".", `file://${outfile}`), { recursive: true });
  writeFileSync(outfile, output, { mode: 0o755 });
  console.log(`Wrote ${outfile.slice(root.length)} (${(output.length / 1024).toFixed(1)} KiB)`);
}
